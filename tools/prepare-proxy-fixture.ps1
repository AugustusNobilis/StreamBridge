param([string]$Directory = "$PSScriptRoot/../.deps/proxy-fixture")
$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force $Directory | Out-Null
$Directory = (Resolve-Path $Directory).Path
$caKey = [Security.Cryptography.RSA]::Create(2048)
$caRequest = [Security.Cryptography.X509Certificates.CertificateRequest]::new('CN=StreamBridge socket test CA', $caKey, [Security.Cryptography.HashAlgorithmName]::SHA256, [Security.Cryptography.RSASignaturePadding]::Pkcs1)
$caRequest.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509BasicConstraintsExtension]::new($true, $false, 0, $true))
$caRequest.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509KeyUsageExtension]::new('KeyCertSign, CrlSign', $true))
$ca = $caRequest.CreateSelfSigned([DateTimeOffset]::UtcNow.AddMinutes(-5), [DateTimeOffset]::UtcNow.AddHours(4))
$key = [Security.Cryptography.RSA]::Create(2048)
$request = [Security.Cryptography.X509Certificates.CertificateRequest]::new('CN=localhost', $key, [Security.Cryptography.HashAlgorithmName]::SHA256, [Security.Cryptography.RSASignaturePadding]::Pkcs1)
$san = [Security.Cryptography.X509Certificates.SubjectAlternativeNameBuilder]::new()
$san.AddDnsName('localhost')
$san.AddIpAddress([Net.IPAddress]::Loopback)
$request.CertificateExtensions.Add($san.Build())
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509BasicConstraintsExtension]::new($false, $false, 0, $true))
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509KeyUsageExtension]::new('DigitalSignature, KeyEncipherment', $true))
$eku = [Security.Cryptography.OidCollection]::new()
[void]$eku.Add([Security.Cryptography.Oid]::new('1.3.6.1.5.5.7.3.1'))
$request.CertificateExtensions.Add([Security.Cryptography.X509Certificates.X509EnhancedKeyUsageExtension]::new($eku, $true))
$serial = [Security.Cryptography.RandomNumberGenerator]::GetBytes(16)
$cert = $request.Create($ca, [DateTimeOffset]::UtcNow.AddMinutes(-5), [DateTimeOffset]::UtcNow.AddHours(2), $serial)
[IO.File]::WriteAllText((Join-Path $Directory 'ca.crt'), $ca.ExportCertificatePem())
[IO.File]::WriteAllText((Join-Path $Directory 'trusted.crt'), $cert.ExportCertificatePem())
[IO.File]::WriteAllText((Join-Path $Directory 'trusted.key'), $key.ExportPkcs8PrivateKeyPem())
$cert.Dispose()
$ca.Dispose()
$key.Dispose()
$caKey.Dispose()
Write-Output 'Private CA and localhost leaf prepared. No Windows trust store was changed.'
